_RX = [(slug, re.compile(p)) for slug, p in _RULES]


def guess_icon(name, site=None):
    """商品名からアイコンの slug を推定する。当てはまらなければ None。

    回転寿司（site="sushi"）は、名前で別の種類と分かるもの（麺・スイーツ・ドリンク・揚げ物など）以外を寿司とみなす。
    """
    n = re.sub(r"[\s　]+", " ", name or "").strip()
    n = re.sub(r"\S*監修", " ", n)  # 「おにぎり浅草宿六監修 豚汁」のように、監修店の名前に釣られないようにする
    for slug, rx in _RX:
        if rx.search(n):
            if site == "sushi" and (slug in ("onigiri", "bento", "sandwich")
                                    or (slug == "salad" and re.search(r"軍艦|巻", n))
                                    or (slug == "sozai" and "漬" in n and not re.search(r"酢漬け|ピクルス", n))):
                return "sushi"  # サラダ軍艦・いなり等。寿司屋の商品はまず寿司として扱う
            return slug
    if site == "sushi":
        return "sushi"
    return None
